// String -> texto
let saudacao = 'Olá, mundo!';
console.log(saudacao);

// Number -> 1, 2.2
let idade = 18;
console.log("Essa é minha idade:", idade);

// Boolean -> verdadeiro ou falso
let logado = true;
console.log("Está logado:", logado);

// Null -> valor nuol (intencionalmente vazio)
let resposta = null;
console.log(resposta);